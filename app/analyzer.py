# У аккаунта 30 000 токенов в минуту на gpt-4o, а один разговор занимает около
# трёх тысяч. Значит больше десятка запросов в минуту не пройдёт. Две ступени
# просева удваивают счёт, и без общей выдержки замер упирается в 429, а в
# работе звонки теряются в час пик. Ограничитель общий на все обращения к
# модели, потому что считать темп в каждом вызывающем месте — значит рано или
# поздно где-то забыть.
_RATE_LOCK = threading.Lock()
_LAST_CALL = 0.0
MIN_CALL_INTERVAL_SEC = 6.0


def pace_calls() -> None:
    """Не выпускать запросы к модели чаще, чем раз в MIN_CALL_INTERVAL_SEC."""
    global _LAST_CALL
    with _RATE_LOCK:
        wait = _LAST_CALL + MIN_CALL_INTERVAL_SEC - time.monotonic()
        if wait > 0:
            time.sleep(wait)
        _LAST_CALL = time.monotonic()


# Цены OpenAI за миллион токенов, доллары. Держать в курсе руками: тарифы
# меняются, а считать по памяти — как раз тот случай, когда «почему кончился
# бюджет» выясняется раскопками по логам.
PRICES: dict[str, tuple[float, float]] = {
    "gpt-4o": (2.50, 10.00),
    "gpt-4o-mini": (0.15, 0.60),
    "gpt-4.1": (2.00, 8.00),
    "gpt-4.1-mini": (0.40, 1.60),
}

USAGE_LOG = "openai_usage.jsonl"


def log_usage(response: Any, *, kind: str, model: str, data_dir: str | None = None) -> None:
    """Записать, во что обошёлся запрос к модели.

    Свой учёт нужен потому, что OpenAI отдаёт расход только по админскому
    ключу, а рабочий его не видит. Без этой записи вопрос «куда ушёл бюджет»
    решается раскопками по логам — один раз так и вышло.
    """
    usage = getattr(response, "usage", None)
    if usage is None:
        return
    prompt_tokens = int(getattr(usage, "prompt_tokens", 0) or 0)
    completion_tokens = int(getattr(usage, "completion_tokens", 0) or 0)
    cached = 0
    details = getattr(usage, "prompt_tokens_details", None)
    if details is not None:
        cached = int(getattr(details, "cached_tokens", 0) or 0)
    price_in, price_out = PRICES.get(model, (0.0, 0.0))
    # Кешированный ввод у OpenAI идёт за половину цены.
    cost = ((prompt_tokens - cached) * price_in + cached * price_in / 2
            + completion_tokens * price_out) / 1e6
    record = {
        "at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "kind": kind, "model": model,
        "in": prompt_tokens, "cached": cached, "out": completion_tokens,
        "usd": round(cost, 5),
    }
    try:
        path = Path(data_dir or _usage_dir()) / USAGE_LOG
        path.parent.mkdir(parents=True, exist_ok=True)
        with path.open("a", encoding="utf-8") as fh:
            fh.write(json.dumps(record, ensure_ascii=False) + "\n")
    except OSError as exc:  # учёт не должен ронять разбор
        logger.debug("учёт расхода не записан: %s", exc)


def _usage_dir() -> str:
    """Каталог данных — тот же, где база. Настройки сюда не тащим: разбор
    вызывается и из скриптов, и из сервиса, а путь один и тот же."""
    from app.config import get_settings

    return str(Path(get_settings().db_path).parent)


