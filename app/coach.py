def assess_call(text: str, meta: dict[str, Any], dept: str, *, api_key: str, model: str) -> dict[str, Any] | None:
    skills = "\n".join(f"- {k}: {v}" for k, v in SKILLS[dept].items())
    rules, fields = EXTRA[dept]
    static = CALL_STATIC.format(role=ROLE[dept], skills=skills, extra_rules=rules, extra_fields=fields)
    dynamic = (f"Звонок: {meta.get('date', '')} {meta['when']}, длительность {meta['dur']} с, номер собеседника {meta['phone']}.\n\n"
               f"РАСШИФРОВКА:\n{text}")
    raw = спросить_claude_с_кэшем(static, dynamic, api_key=api_key, model=model, kind="тренер-звонок", max_tokens=2400)
    return clean(raw, text, dept) if isinstance(raw, dict) else None


def day_summary(rows: list[dict[str, Any]], stats: dict[str, Any], dept: str, *, api_key: str, model: str) -> str:
    lines = [f"Всего звонков за день: {stats['all']}, разговоров от 20 секунд: {stats['talk']}, "
             f"по делу: {stats['relevant']}, суммарное время разговоров: {stats['minutes']} мин."]
    if stats.get("extra"):
        lines.append("ЦИФРЫ: " + "; ".join(f"{k}: {v}" for k, v in stats["extra"].items()))
    avg = stats.get("skill_avg") or {}
    if avg:
        lines.append("Средний балл навыков (0-2): " + "; ".join(f"{SKILLS[dept][k]} — {v}" for k, v in avg.items()))
    for i, r in enumerate(rows, 1):
        a = r["a"]
        lines.append(f"\nЗвонок №{i} ({r['when']}, {r['dur']} с, {r['phone']}): {a.get('summary','')} Итог: {a.get('outcome','')}."
                     + (f" Упущен шанс." if a.get("lost_chance") else ""))
        for g in a.get("good", []):
            lines.append(f"  + {g['what']} («{g['quote']}»)")
        for b in a.get("bad", []):
            lines.append(f"  - {b['what']} («{b['quote']}»). Лучше: {b.get('better','')}")
        if a.get("attention"):
            lines.append(f"  ! внимание: {a['attention']}")
        for o in a.get("objects") or []:
            lines.append(f"  объект: {o.get('where','?')} — {o.get('work','?')}, старт: {o.get('when','?')}")
        if a.get("new_need"):
            lines.append("  новая потребность у клиента")
        if a.get("next_contact"):
            lines.append(f"  договорённость о контакте: {a['next_contact']}")
        crm = r.get("crm")
        if crm is not None:
            if crm.get("comment"):
                lines.append(f"  запись менеджера в CRM за этот день: «{crm['comment']}»")
            else:
                lines.append("  запись менеджера в CRM за этот день: НЕТ" + (f" (в поле последний комментарий стоит: «{crm['last_comment']}»)" if crm.get("last_comment") else ""))
            ex = [f"{k}: {v}" for k, v in (("звонок состоялся", crm.get("state")), ("что спрашивал", crm.get("asked")),
                                          ("живая заявка", crm.get("live")), ("КП отправлено", crm.get("kp"))) if v]
            if ex:
                lines.append("  отметки менеджера в карточке: " + "; ".join(ex))
        if a.get("needs_owner"):
            lines.append(f"  подключить руководителя: {a['needs_owner']} (менеджер сам предложил: {'да' if a.get('owner_offered') else 'нет'})")
    static = DAY_HEAD.format(role=ROLE[dept]) + "\n\n" + DAY_BODY[dept] + DAY_TAIL.replace("{{", "{").replace("}}", "}")
    raw = спросить_claude_с_кэшем(static, "\n".join(lines), api_key=api_key, model=model, kind="тренер-день", max_tokens=4000)
    return str(raw.get("report") or "") if isinstance(raw, dict) else ""


def ensure_tables(conn: sqlite3.Connection) -> None:
    conn.execute("""CREATE TABLE IF NOT EXISTS coach_calls (
        call_uid TEXT PRIMARY KEY, vats_login TEXT NOT NULL, local_date TEXT NOT NULL,
        result_json TEXT NOT NULL, model TEXT, created_at TEXT NOT NULL)""")
    conn.execute("""CREATE TABLE IF NOT EXISTS coach_reports (
        vats_login TEXT NOT NULL, local_date TEXT NOT NULL, text TEXT NOT NULL,
        stats_json TEXT, created_at TEXT NOT NULL, PRIMARY KEY (vats_login, local_date))""")
    conn.commit()


def now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")
