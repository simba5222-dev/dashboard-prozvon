def _norm(s: str) -> str:
    return re.sub(r"\s+", " ", re.sub(r"[^\w\s]", "", (s or "").lower())).strip()


def _quote_ok(quote: str, text_norm: str) -> bool:
    q = _norm(quote)
    return len(q) >= 6 and q in text_norm


def clean(result: dict[str, Any], text: str, dept: str) -> dict[str, Any]:
    """Выбросить пункты без проверенной цитаты и неизвестные навыки."""
    tn = _norm(text)
    known = SKILLS[dept]
    out = dict(result)
    nd = str(result.get("next_date") or "").strip()
    out["next_date"] = nd if re.fullmatch(r"\d{4}-\d{2}-\d{2}", nd) else ""
    if str(result.get("contact_pref") or "").strip().lower() not in ("раз в месяц", "не звонить"):
        out["contact_pref"] = "обычно"
    out["skills"] = {k: v for k, v in (result.get("skills") or {}).items() if k in known and v in (0, 1, 2, None)}
    for key in ("good", "bad"):
        out[key] = [p for p in (result.get(key) or []) if isinstance(p, dict) and _quote_ok(p.get("quote", ""), tn)][:2]
    return out


