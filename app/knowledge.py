def questions_for(text: str) -> list[str]:
    """Обязательные вопросы по технике, которая упоминается в тексте.

    Грубый отбор по названиям: разбор всё равно делает модель, а этот список
    нужен, чтобы подсунуть ей правильный чек-лист, а не весь учебник разом.
    """
    lowered = (text or "").lower()
    aliases = {
        "гусянк": "гусеничный экскаватор",
        "петушок": "экскаватор-погрузчик",
        "бобкэт": "фронтальный погрузчик",
        "маник": "манипулятор",
        "вышк": "автовышка",
        "кран": "автокран",
        "фрез": "дорожная фреза",
        "укладчик": "асфальтоукладчик",
        "самосвал": "самосвал",
        "пухто": "пухто",
        "трал": "трал",
        "бульдозер": "бульдозер",
    }
    found: list[str] = []
    for key, questions in REQUIRED_QUESTIONS.items():
        if key in lowered:
            found.extend(questions)
    for alias, key in aliases.items():
        if alias in lowered and key in REQUIRED_QUESTIONS:
            found.extend(REQUIRED_QUESTIONS[key])
    # Порядок сохраняем, повторы убираем: один и тот же вопрос мог прийти и по
    # названию техники, и по жаргонному прозвищу.
    seen: set[str] = set()
    out = []
    for question in found:
        if question not in seen:
            seen.add(question)
            out.append(question)
    return out


def upsell_for(text: str) -> list[str]:
    """Что стоило предложить в дополнение — по технике из разговора."""
    lowered = (text or "").lower()
    return [f"{name}: {advice}" for name, advice in UPSELL.items() if name in lowered]
