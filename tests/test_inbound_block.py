"""Открытая заявка глушит новый запрос только на ту же технику."""

from app.inbound import lead_block_reason


def заявка(техника: str, имя: str = "старая"):
    return {"id": "1", "name": имя, "equipment": техника}


def test_другая_техника_не_блокирует():
    """Правило владельца 02.10.2026.

    Замер за две недели: из 21 отказа «у клиента открыта заявка» восемь были
    новыми заявками на другую технику — от клиентов, с которыми мы уже
    работаем, то есть от самых тёплых.
    """
    assert lead_block_reason([заявка("Автокран")], "экскаватор-погрузчик") == ""
    assert lead_block_reason([заявка("Автовышка")], "нерудка") == ""
    assert lead_block_reason([заявка("Гусеничный экскаватор")], "каток") == ""


def test_та_же_техника_блокирует():
    assert lead_block_reason([заявка("Автокран")], "автокран") != ""
    assert lead_block_reason([заявка("Гусеничный Экскаватор")], "гусеничный экскаватор") != ""


def test_одно_семейство_блокирует():
    assert lead_block_reason([заявка("Виброплита")], "вибротрамбовка") != ""
    assert lead_block_reason([заявка("Автокран")], "кран") != ""
    assert lead_block_reason([заявка("Кран-манипулятор")], "манипулятор") != ""


def test_экскаваторы_разделены():
    """Решение владельца 02.10.2026: в справочнике Synergy это четыре машины —
    гусеничный (2), длиннорукий гусеничный (6), мини (5) и
    экскаватор-погрузчик (84)."""
    assert lead_block_reason([заявка("Гусеничный Экскаватор")], "экскаватор-погрузчик") == ""
    assert lead_block_reason([заявка("Гусеничный Экскаватор")], "мини экскаватор") == ""
    assert lead_block_reason([заявка("Гусеничный Экскаватор")],
                             "длиннорукий гусеничный экскаватор") == ""


def test_жаргон_узнаётся():
    """«Гусь» — гусеничный экскаватор, «фронтальник» — фронтальный погрузчик."""
    assert lead_block_reason([заявка("Гусеничный Экскаватор")], "гусь") != ""
    assert lead_block_reason([заявка("Экскаватор погрузчик")], "фронтальник") == ""


def test_слишком_общее_название_блокирует():
    """Голое «экскаватор» может значить любую из четырёх машин — не рискуем."""
    assert lead_block_reason([заявка("Гусеничный Экскаватор")], "экскаватор") != ""


def test_кран_и_манипулятор_разные():
    """Поправка владельца 02.10.2026: это разные типы транспорта.

    В справочнике Synergy у них разные номера — 18 и 22. Без явного правила
    «кран» слипся бы с «кран-манипулятором» по вхождению подстроки.
    """
    assert lead_block_reason([заявка("Манипулятор")], "кран") == ""
    assert lead_block_reason([заявка("Автокран")], "манипулятор") == ""


def test_расплывчатое_название_блокирует():
    """Просев не понял, что просят, — заводить по этому новую заявку нельзя."""
    assert lead_block_reason([заявка("Автовышка")], "машина") != ""
    assert lead_block_reason([заявка("Автовышка")], "") != ""


def test_без_открытых_заявок_не_блокирует():
    assert lead_block_reason([], "автокран") == ""


def test_признак_создано_ии_только_на_свою_заявку():
    """Правило владельца 02.10.2026.

    Поле «признак» различает, откуда взялась заявка: «Реклама» — её создала
    автоматизация CRM по звонку на общий номер, пусто — менеджер завёл сам,
    «Создано ИИ» — завёл разбор звонка. Пометить им чужую заявку, которую мы
    только дописали, значит приписать себе работу менеджера.
    """
    from app.crm_write import FIELD_MARK, MARK_AI, order_customs

    разбор = {"transport_type": "Автокран"}
    своя = order_customs(разбор, "расшифровка", "выжимка", наша=True)
    чужая = order_customs(разбор, "расшифровка", "выжимка")
    assert своя[FIELD_MARK] == [MARK_AI]
    assert FIELD_MARK not in чужая
