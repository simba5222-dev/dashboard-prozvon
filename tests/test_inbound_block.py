"""Открытая заявка глушит новый запрос только на ту же технику."""

from app.inbound import lead_block_reason


def заявка(техника: str, имя: str = "старая"):
    return {"id": "1", "name": имя, "equipment": техника}


def test_другая_техника_не_блокирует():
    """Правило владельца 02.10.2026.

    Замер за две недели: из 21 отказа «у клиента открыта заявка» восемь были
    новыми заявками на другую технику — от клиентов, с которыми мы уже
    работаем, то есть от самых тёплых.
    """
    assert lead_block_reason([заявка("Автокран")], "экскаватор-погрузчик") == ""
    assert lead_block_reason([заявка("Автовышка")], "нерудка") == ""
    assert lead_block_reason([заявка("Гусеничный экскаватор")], "каток") == ""


def test_та_же_техника_блокирует():
    assert lead_block_reason([заявка("Автокран")], "автокран") != ""
    assert lead_block_reason([заявка("Экскаватор")], "гусеничный экскаватор") != ""


def test_одно_семейство_блокирует():
    """«Кран» и «манипулятор» — одна машина, названная по-разному."""
    assert lead_block_reason([заявка("Манипулятор")], "кран") != ""
    assert lead_block_reason([заявка("Виброплита")], "вибротрамбовка") != ""


def test_расплывчатое_название_блокирует():
    """Просев не понял, что просят, — заводить по этому новую заявку нельзя."""
    assert lead_block_reason([заявка("Автовышка")], "машина") != ""
    assert lead_block_reason([заявка("Автовышка")], "") != ""


def test_без_открытых_заявок_не_блокирует():
    assert lead_block_reason([], "автокран") == ""
