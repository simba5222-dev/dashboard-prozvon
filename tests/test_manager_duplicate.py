"""Менеджер не заводит вторую заявку за день на ту же технику.

Решение владельца 09.10.2026, отдельно от lead_block_reason — здесь дубль
смотрит не на заявки клиента, а на то, что сегодня уже завёл сам менеджер.
Семейственное сопоставление техники то же самое (одно_семейство), поэтому
здесь проверяем только то, что отличается от test_inbound_block.py.
"""

from app.inbound import manager_duplicate_reason


def заявка(техника: str, id_: str = "1"):
    return {"id": id_, "equipment": техника}


def test_без_сегодняшних_заявок_не_блокирует():
    assert manager_duplicate_reason([], "автокран") == ""


def test_другая_техника_не_блокирует():
    assert manager_duplicate_reason([заявка("Автокран")], "экскаватор-погрузчик") == ""


def test_та_же_техника_блокирует():
    reason = manager_duplicate_reason([заявка("Автокран")], "автокран")
    assert reason != ""


def test_одно_семейство_блокирует():
    assert manager_duplicate_reason([заявка("Виброплита")], "вибротрамбовка") != ""


def test_расплывчатое_название_блокирует():
    assert manager_duplicate_reason([заявка("Автовышка")], "") != ""


def test_разные_клиенты_одна_техника_всё_равно_блокирует():
    """Правило завязано на менеджера и день, а не на клиента — специально:
    заявки в списке могут быть от разных контактов, это не важно."""
    assert manager_duplicate_reason([заявка("Автокран", "1"), заявка("Манипулятор", "2")],
                                    "автокран") != ""
