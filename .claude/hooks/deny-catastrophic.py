#!/usr/bin/env python3
"""PreToolUse: жёсткий запрет команд, которые здесь неприемлемы никогда.

Механизм, а не заметка в CLAUDE.md: правило в тексте работает первые полчаса
сессии, дальше контекст забит задачей и правило тихо пропускается.

Список держать КОРОТКИМ. Каждая запись — то, что не имеет ни одного законного
применения в этом проекте. Иначе хук превращается в источник ложных
срабатываний, и его начинают обходить.

Как добавить правило:
1. Разобрать строку на сегменты (`;`, `&`, `|`, перевод строки) — чтобы
   безобидная команда не блокировалась из-за похожей подстроки в соседнем
   сегменте.
2. Матчить только там, где команда РЕАЛЬНО вызывается (начало сегмента), а не
   как подстрока внутри echo или grep.
3. В reason объяснить, почему нельзя и что делать вместо этого.
"""
import json
import re
import sys

try:
    data = json.load(sys.stdin)
except Exception:
    sys.exit(0)  # непонятный ввод — не блокируем

cmd = (data.get("tool_input") or {}).get("command", "") or ""
segments = re.split(r"[;&|\n]+", cmd)


def deny(reason: str) -> None:
    print(json.dumps({
        "hookSpecificOutput": {
            "hookEventName": "PreToolUse",
            "permissionDecision": "deny",
            "permissionDecisionReason": reason,
        }
    }))
    sys.exit(0)


def invoked(segment: str, command: str) -> bool:
    """Сегмент действительно вызывает эту команду (можно через sudo и путь)."""
    pattern = rf"^\s*(?:\w+=\S*\s+)*(?:sudo\s+(?:-\S+\s+)*)?(?:\S*/)?{command}\b"
    return bool(re.search(pattern, segment))


for seg in segments:
    # 1. Смена владельца в каталогах проектов. Сервисы asr и таймеры дашборда
    # работают под claude; agent пишет туда по группе и setgid. chown снимает
    # сервису доступ молча — падение обнаружится на следующем запуске таймера.
    if (invoked(seg, "chown") or invoked(seg, "chgrp")) and "/home/claude" in seg:
        deny(
            "ЗАПРЕЩЕНО: chown/chgrp в /home/claude ломает доступ сервисам, которые "
            "работают под пользователем claude (asr.service, таймеры дашборда). "
            "Каталоги открыты группе claude через setgid, у agent umask 002 — "
            "права уже настроены, менять владельца не нужно. Если файл всё же "
            "недоступен, создавайте его через sudo -u claude с umask 002."
        )

    # 2. Удаление данных, которые не воспроизводятся бесплатно: расшифровки и
    # разбор стоили запросов к OpenAI, записи разговоров на боевом сервере
    # хранятся только там.
    if invoked(seg, "rm") and re.search(
        r"(dashboard\.db|/dashboard/data|/opt/asr/data|data/recordings|data/transcripts)", seg
    ):
        deny(
            "ЗАПРЕЩЕНО: это данные, которые нельзя получить заново даром — "
            "расшифровки и разбор оплачены запросами к модели, записи разговоров "
            "лежат только на боевом сервере. Чтобы убрать строки, работайте "
            "запросом к базе, а файл сначала перенесите в сторону, а не удаляйте."
        )

    # 3. Подмена деплой-ключа токеном аккаунта. Ключ ограничен одним
    # репозиторием, токен gh даёт весь аккаунт, а любой файл на этой машине
    # читается агентом с sudo.
    if invoked(seg, "gh") and re.search(r"\bauth\s+login\b", seg):
        deny(
            "ЗАПРЕЩЕНО: gh auth login кладёт на машину токен всего аккаунта GitHub. "
            "Пуш уже работает через деплой-ключ, ограниченный одним репозиторием "
            "(core.sshCommand в конфиге репозитория). Если нужен доступ к другому "
            "репозиторию — заводится отдельный деплой-ключ."
        )

sys.exit(0)
